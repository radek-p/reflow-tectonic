// List or filter an ICU common data package (.dat, format "CmnD").
//   node reflow/deps/icu-data.ts list  in.dat
//   node reflow/deps/icu-data.ts c     in.dat out.c 'regex' ...   -> C source defining icudtNN_dat
// The C file replaces ICU's empty stubdata library, so the wasm engine gets
// just the ICU data items XeTeX needs (line-break rules, converter aliases).
import { readFileSync, writeFileSync } from "node:fs";

const [cmd, input, output, ...patterns] = process.argv.slice(2);
const buf = readFileSync(input);
const headerSize = buf.readUInt16LE(0);
if (buf[2] !== 0xda || buf[3] !== 0x27) throw new Error("not an ICU data file");
if (buf.toString("latin1", 12, 16) !== "CmnD") throw new Error("not a common data package");
if (buf[4 + 4] !== 0) throw new Error("big-endian package not supported");
const toc = headerSize;
const count = buf.readUInt32LE(toc);
interface Item { name: string; data: Buffer }
const items: Item[] = [];
for (let i = 0; i < count; i++) {
  const nameOff = buf.readUInt32LE(toc + 4 + 8 * i);
  const dataOff = buf.readUInt32LE(toc + 8 + 8 * i);
  const next = i + 1 < count ? buf.readUInt32LE(toc + 8 + 8 * (i + 1)) : buf.length - toc;
  const end = buf.indexOf(0, toc + nameOff);
  items.push({ name: buf.toString("latin1", toc + nameOff, end), data: buf.subarray(toc + dataOff, toc + next) });
}

if (cmd === "list") {
  for (const it of items) console.log(`${String(it.data.length).padStart(9)} ${it.name}`);
  process.exit(0);
}

const res = patterns.map((p) => new RegExp(p));
const keep = items.filter((it) => res.some((r) => r.test(it.name)));
// Rebuild: same header, then TOC {count, (nameOffset, dataOffset)*}, names, items (16-aligned).
const align = (n: number) => (n + 15) & ~15;
const names = Buffer.concat(keep.map((it) => Buffer.from(it.name + "\0", "latin1")));
let off = align(4 + 8 * keep.length + names.length);
const tocBuf = Buffer.alloc(off);
tocBuf.writeUInt32LE(keep.length, 0);
let nameOff = 4 + 8 * keep.length;
names.copy(tocBuf, nameOff);
const parts: Buffer[] = [buf.subarray(0, headerSize), tocBuf];
keep.forEach((it, i) => {
  tocBuf.writeUInt32LE(nameOff, 4 + 8 * i);
  tocBuf.writeUInt32LE(off, 8 + 8 * i);
  nameOff += Buffer.byteLength(it.name, "latin1") + 1;
  const padded = Buffer.alloc(align(it.data.length));
  it.data.copy(padded);
  parts.push(padded);
  off += padded.length;
});
const out = Buffer.concat(parts);
const sym = /icudt(\d+)/.exec(keep[0]?.name ?? "icudt68")![0] + "_dat";
const lines: string[] = [];
for (let i = 0; i < out.length; i += 32) lines.push(Array.from(out.subarray(i, i + 32)).join(","));
writeFileSync(output, `/* Generated by reflow/deps/icu-data.ts from ${input.split("/").pop()}: ` +
  `${keep.length} of ${items.length} items, ${out.length} bytes. */\n` +
  `#include <stdint.h>\n__attribute__((aligned(16))) const uint8_t ${sym}[${out.length}] = {\n${lines.join(",\n")}\n};\n`);
for (const it of keep) console.log(`${String(it.data.length).padStart(9)} ${it.name}`);
console.log(`${keep.length} items, ${out.length} bytes -> ${output} (${sym})`);
